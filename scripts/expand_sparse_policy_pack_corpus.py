def build_rules_for_pack(slug: str, prefix: str, framework: str) -> list[dict[str, Any]]:
    specs = RULE_SPECS[slug]
    if len(specs) != RULE_COUNT:
        raise ValueError(f"{slug}: expected {RULE_COUNT} rules, found {len(specs)}")

    rules: list[dict[str, Any]] = []
    for index, (title, description, remediation, theme, severity, azure) in enumerate(specs, start=1):
        rule_id = f"{prefix}-{index:03d}"
        priority = assign_rule_priority(index, RULE_COUNT)
        rules.append(
            build_rule(
                rule_id,
                title=title,
                description=description,
                remediation_guidance=remediation,
                framework=framework,
                theme=theme,
                severity=severity,
                priority=priority,
                azure=azure,
            )
        )
    return rules


def build_curated_document(slug: str, metadata: dict[str, str], rules: list[dict[str, Any]]) -> dict[str, Any]:
    return {
        "schemaVersion": 1,
        "kind": "archlucid.policyPack.curatedRules.v1",
        "pack": {
            "name": metadata["displayName"],
            "description": metadata["description"],
            "version": PACK_VERSION,
            "category": metadata["category"],
            "isDefault": True,
            "suggestedPackType": "PlatformDefault",
            "policyPackContentDocumentPath": f"docs/samples/policy-packs/{slug}.json",
        },
        "rules": rules,
    }


def main() -> None:
    generator_packs = load_generator_packs()
    summary: list[tuple[str, int]] = []

    for slug in EXPAND_SLUGS:
        if slug not in generator_packs:
            raise KeyError(f"Pack slug not found in generator PACKS: {slug}")
        if slug not in RULE_SPECS:
            raise KeyError(f"Missing RULE_SPECS corpus for slug: {slug}")

        pack = generator_packs[slug]
        metadata = load_pack_metadata(slug, generator_packs)
        rules = build_rules_for_pack(slug, pack["prefix"], pack["framework"])
        document = build_curated_document(slug, metadata, rules)

        output_path = SAMPLES / f"{slug}-rules-v1.json"
        output_path.write_text(json.dumps(document, indent=2) + "\n", encoding="utf-8")
        summary.append((slug, len(rules)))

    print("expand_sparse_policy_pack_corpus summary:")
    for slug, count in summary:
        print(f"  {slug}: {count} rules")
    print(f"total packs written: {len(summary)}")
    print(f"total rules written: {sum(count for _, count in summary)}")


if __name__ == "__main__":
    main()
