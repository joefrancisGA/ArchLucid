def assign_rule_priority(index: int, total: int) -> str:
    if total <= 0:
        return "P1"
    p0_count = max(1, total // 5)
    p1_count = max(1, (total * 2) // 5)

    if index <= p0_count:
        return "P0"
    if index <= p0_count + p1_count:
        return "P1"
    return "P2"


def load_generator_packs() -> dict[str, dict[str, Any]]:
    generator_path = REPO / "scripts" / "generate_v1_bundled_policy_packs.py"
    spec = importlib.util.spec_from_file_location("generate_v1_bundled_policy_packs", generator_path)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"Unable to load generator module from {generator_path}")
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return {pack["slug"]: pack for pack in module.PACKS}


def load_pack_metadata(slug: str, generator_packs: dict[str, dict[str, Any]]) -> dict[str, str]:
    rules_path = SAMPLES / f"{slug}-rules-v1.json"
    if rules_path.exists():
        existing = json.loads(rules_path.read_text(encoding="utf-8"))
        pack = existing.get("pack", {})
        if pack.get("name") and pack.get("description") and pack.get("category"):
            return {
                "displayName": pack["name"],
                "description": pack["description"],
                "category": pack["category"],
                "disclaimer": pack.get("disclaimer", ""),
            }

    source = generator_packs[slug]
    return {
        "displayName": source["displayName"],
        "description": source["description"],
        "category": source["category"],
        "disclaimer": source.get("disclaimer", ""),
    }


def evidence_hints(azure: bool = False, extra: list[str] | None = None) -> list[str]:
    hints = list(STANDARD_EVIDENCE_HINTS)
    if azure:
        for hint in AZURE_EVIDENCE_HINTS:
            if hint not in hints:
                hints.append(hint)
    if extra:
        for hint in extra:
            if hint not in hints:
                hints.append(hint)
    return hints


def build_rule(
    rule_id: str,
    *,
    title: str,
    description: str,
    remediation_guidance: str,
    framework: str,
    theme: str,
    severity: str,
    priority: str,
    azure: bool = False,
    extra_hints: list[str] | None = None,
) -> dict[str, Any]:
    return {
        "id": rule_id,
        "title": title,
        "description": description,
        "severity": severity,
        "priority": priority,
        "remediationGuidance": remediation_guidance,
        "evidenceHints": evidence_hints(azure=azure, extra=extra_hints),
        "frameworkMappings": [{"framework": framework, "theme": theme}],
    }


