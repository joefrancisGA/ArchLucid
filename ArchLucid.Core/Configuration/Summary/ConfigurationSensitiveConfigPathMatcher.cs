    }

    private static bool IsUnPrefixedNegation(ReadOnlySpan<char> segment, int fragmentIndex)
    {
        ReadOnlySpan<char> before = segment.Slice(0, fragmentIndex);

        if (before.Length < 2)
            return false;

        return before.EndsWith("un", StringComparison.OrdinalIgnoreCase);
