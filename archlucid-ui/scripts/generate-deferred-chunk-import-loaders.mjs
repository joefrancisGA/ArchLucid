/**
 * Build-time: emits static `import()` loaders from deferred chunk manifest metadata.
 * Writes src/lib/operator/deferred-chunk-import-loaders.generated.ts
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const UI_ROOT = join(__dirname, "..");
const OPERATOR_LIB_DIR = join(UI_ROOT, "src", "lib", "operator");
const OUT_PATH = join(OPERATOR_LIB_DIR, "deferred-chunk-import-loaders.generated.ts");

/** Stable manifest merge order — keep in sync with deferred-chunk-manifest.ts. */
const MANIFEST_FILE_ORDER = [
  "operator-home-chunk-manifest.ts",
  "reviews-hub-chunk-manifest.ts",
  "reviews-new-chunk-manifest.ts",
  "run-detail-chunk-manifest.ts",
  "governance-workflow-chunk-manifest.ts",
  "governance-findings-chunk-manifest.ts",
  "policy-packs-authoring-chunk-manifest.ts",
  "alert-rules-hub-chunk-manifest.ts",
  "signed-records-list-chunk-manifest.ts",
  "sponsor-roi-dashboard-chunk-manifest.ts",
  "alerts-inbox-chunk-manifest.ts",
  "app-shell-chunk-manifest.ts",
  "operator-shell-top-bar-chunk-manifest.ts",
  "marketing-chunk-manifest.ts",
];

/**
 * @param {string} content
 * @returns {{ id: string; modulePath: string; exportName: string }[]}
 */
function parseChunkManifestEntries(content) {
  /** @type {{ id: string; modulePath: string; exportName: string }[]} */
  const entries = [];

  for (const block of content.matchAll(/\{([^{}]+)\}/g)) {
    const body = block[1];
    const id = body.match(/id:\s*"([^"]+)"/)?.[1];
    const modulePath = body.match(/modulePath:\s*"([^"]+)"/)?.[1];
    const exportName = body.match(/exportName:\s*"([^"]+)"/)?.[1];

    if (id !== undefined && modulePath !== undefined && exportName !== undefined) {
      entries.push({ id, modulePath, exportName });
    }
  }

  return entries;
}

/**
 * @param {{ id: string; modulePath: string; exportName: string }} entry
 */
function renderSwitchCase(entry) {
  return `    case "${entry.id}":
      return deferredChunkLoader(() =>
        import("${entry.modulePath}").then(
          (module) => module.${entry.exportName},
        ),
      ) as () => Promise<ComponentType<Record<string, unknown>>>;`;
}

/**
 * @param {{ id: string; modulePath: string; exportName: string }[]} entries
 */
function renderGeneratedSource(entries) {
  const switchCases = entries.map(renderSwitchCase).join("\n");

  return `/**
 * Generated by \`scripts/generate-deferred-chunk-import-loaders.mjs\`. Do not edit by hand.
 * Run: \`npm run generate:deferred-chunk-loaders\`
 */
import type { ComponentType } from "react";

import { deferredChunkLoader } from "@/lib/import-deferred-chunk-with-retry";

/** Static import map so webpack can split deferred chunks predictably. */
export function resolveDeferredChunkImportLoader(
  entryId: string,
): () => Promise<ComponentType<Record<string, unknown>>> {
  switch (entryId) {
${switchCases}
    default:
      throw new Error(\`No deferred chunk import loader registered for manifest entry "\${entryId}".\`);
  }
}
`;
}

/** @returns {{ id: string; modulePath: string; exportName: string }[]} */
export function collectDeferredChunkManifestEntries() {
  const operatorFiles = new Set(readdirSync(OPERATOR_LIB_DIR));
  /** @type {{ id: string; modulePath: string; exportName: string }[]} */
  const entries = [];

  for (const manifestFile of MANIFEST_FILE_ORDER) {
    if (!operatorFiles.has(manifestFile)) {
      throw new Error(`Missing expected chunk manifest file: ${manifestFile}`);
    }

    const content = readFileSync(join(OPERATOR_LIB_DIR, manifestFile), "utf8");
    entries.push(...parseChunkManifestEntries(content));
  }

  const ids = entries.map((entry) => entry.id);
  const uniqueIds = new Set(ids);

  if (uniqueIds.size !== ids.length) {
    const duplicates = ids.filter((id, index) => ids.indexOf(id) !== index);
    throw new Error(`Duplicate deferred chunk manifest ids: ${[...new Set(duplicates)].join(", ")}`);
  }

  return entries;
}

export function generateDeferredChunkImportLoadersSource() {
  return renderGeneratedSource(collectDeferredChunkManifestEntries());
}

const generated = generateDeferredChunkImportLoadersSource();
const entryCount = collectDeferredChunkManifestEntries().length;
writeFileSync(OUT_PATH, generated, "utf8");
console.log(`Wrote ${OUT_PATH} (${entryCount} loaders)`);
