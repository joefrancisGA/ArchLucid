"use client";

import { SecureNowPartialCaptureRecoveryParagraph } from "@/components/product-line/SecureNowPartialCaptureRecoveryLinks";
import { useLatestPartialCaptureSnapshotId } from "@/hooks/use-latest-partial-capture-snapshot-id";
import { useLatestSnapshotCaptureIsPartial } from "@/hooks/use-latest-snapshot-capture-partial";
import { useSecureNowPartialCaptureReturnPath } from "@/hooks/use-securenow-partial-capture-return-path";
import { SEARCH_REVIEW_EVIDENCE_EMPTY_PARTIAL_CAPTURE_LINE } from "@/lib/insights/search-review-evidence-empty-partial-capture-copy";

export function SearchReviewEvidencePartialEmptyHonesty(): React.JSX.Element | null {
  const partialCapture = useLatestSnapshotCaptureIsPartial(true);
  const partialCaptureSnapshotId = useLatestPartialCaptureSnapshotId(partialCapture);
  const partialCaptureReturnPath = useSecureNowPartialCaptureReturnPath();

  if (!partialCapture) {
    return null;
  }

  return (
    <SecureNowPartialCaptureRecoveryParagraph
      testId="search-review-evidence-empty-partial-capture"
      partialCaptureSnapshotId={partialCaptureSnapshotId}
      returnPath={partialCaptureReturnPath}
      middleLine={SEARCH_REVIEW_EVIDENCE_EMPTY_PARTIAL_CAPTURE_LINE}
      cloudConnectionsTestId="search-review-evidence-empty-partial-capture-cloud"
      extractUploadTestId="search-review-evidence-empty-partial-capture-extract"
    />
  );
}